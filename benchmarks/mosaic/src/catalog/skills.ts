const steps = (items: readonly string[]): string =>
  items.map((item, index) => `${index + 1}. ${item}`).join('\n');

const materialize = (
  domain: CatalogDomain,
  prefix: string,
  seeds: readonly SkillSeed[],
): readonly MicroSkill[] =>
  seeds.map((seed) => ({
    id: `${prefix}.${seed.slug}`,
    domain,
    title: seed.title,
    description: seed.description,
    body: `# Outcome\n\n${seed.description}\n\n# Procedure\n\n${steps(seed.procedure)}`,
    allowedTools: seed.tools,
    relations: [
      {
        kind: seed.relation,
        skillId: `${prefix}.${seed.peer}`,
        rationale: seed.rationale,
      },
    ],
  }));

